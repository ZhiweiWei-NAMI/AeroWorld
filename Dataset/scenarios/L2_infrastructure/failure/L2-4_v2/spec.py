def _trigger(data):
    allowed = set(TriggerSpec.__dataclass_fields__)
    cleaned = {key: value for key, value in data.items() if key in allowed}
    return TriggerSpec(**cleaned)


def _action(data):
    return ActionSpec(data["type"], data.get("params", {}))


